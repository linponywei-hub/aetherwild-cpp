"""Compile authored JSON into the C++ binary; no runtime paths or JS rules required."""
import json,pathlib
root=pathlib.Path(__file__).resolve().parents[1]
bundle={}
for p in sorted((root/'data/content').glob('*.json')):
 value=json.loads(p.read_text(encoding='utf-8'))
 if isinstance(value,list) and value and all(isinstance(v,dict) and 'id' in v for v in value):
  assert len({v['id'] for v in value})==len(value),p
  value={v['id']:v for v in value}
 bundle[p.stem]=value
text=json.dumps(bundle,ensure_ascii=False,separators=(',',':'))
# Separate append expressions keep each source literal within MSVC's literal limit.
header='// Generated by tools/generate_content.py; edit data/content instead.\n#include "aetherwild/content.hpp"\n'

parts=[]
for i,start in enumerate(range(0,len(text),120000)):
 name='contentPayload'+str(i);parts.append(name)
 lines=[header,'namespace aw { std::string '+name+'(){ std::string text;']
 part=text[start:start+120000]
 for offset in range(0,len(part),3000):
  chunk=part[offset:offset+3000]
  assert ')AWCONTENT"' not in chunk
  lines.append('text+=R"AWCONTENT('+chunk+')AWCONTENT";')
 lines+=['return text; } }']
 output=root/'src'/('content_payload_'+str(i).zfill(3)+'.cpp'); compiled='\n'.join(lines)+'\n'
 if not output.exists() or output.read_text(encoding='utf-8')!=compiled:output.write_text(compiled,encoding='utf-8')
lines=[header,'namespace aw {']+['std::string '+name+'();' for name in parts]
lines+=['const Json& contentBundle(){ static const Json data=[] { std::string text;']
lines+=['text+='+name+'();' for name in parts]
lines+=['return Json::parse(text); }(); return data; } }']
output=root/'src/content_data.cpp';compiled='\n'.join(lines)+'\n'
if not output.exists() or output.read_text(encoding='utf-8')!=compiled:output.write_text(compiled,encoding='utf-8')
for old in (root/'src').glob('content_payload_*.cpp'):
 if int(old.stem.rsplit('_',1)[1])>=len(parts):old.unlink()
print('Compiled content bytes:',len(text.encode('utf-8')),'fragments:',len(parts))
