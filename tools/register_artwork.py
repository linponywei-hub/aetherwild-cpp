"""Validate and register named generated PNG assets. JSON records arrive on stdin."""
import hashlib,json,pathlib,sys
import fcntl
from PIL import Image
root=pathlib.Path(__file__).resolve().parents[1]
manifest_path=root/'data/artwork/manifest.json'
lock=open('/tmp/aetherwild-artwork-register.lock','w')
fcntl.flock(lock,fcntl.LOCK_EX)
manifest=json.loads(manifest_path.read_text())
for record in json.load(sys.stdin):
 entry=manifest['entries'][record['id']]
 image=Image.open(record['source'])
 if image.format!='PNG' or image.mode!='RGBA':raise ValueError('Expected RGBA PNG: '+entry['id'])
 alpha=image.getchannel('A');hist=alpha.histogram()
 if hist[0]<image.width*image.height*.1 or alpha.getextrema()[1]<200:raise ValueError('No verified cutout alpha: '+entry['id'])
 destination=root/entry['path'];destination.parent.mkdir(parents=True,exist_ok=True)
 image.thumbnail((512,342),Image.Resampling.LANCZOS);image.save(destination,optimize=True)
 entry.update(status='ready',sha256=hashlib.sha256(destination.read_bytes()).hexdigest(),size=list(image.size),transparentPixels=image.getchannel('A').histogram()[0],prompt=record.get('prompt','Approved Star-gold Pickaxe preview'))
manifest_path.write_text(json.dumps(manifest,ensure_ascii=False,indent=2)+'\n')
ready={id:'/art/items/'+id+'.png' for id,e in manifest['entries'].items() if e['status']=='ready'}
(root/'web/modules/artwork/artwork-index.js').write_text('// Generated by tools/register_artwork.py; exact catalogue IDs only.\nexport const artwork='+json.dumps(ready,ensure_ascii=False,sort_keys=True)+';\n')
names={id:e['name'] for id,e in manifest['entries'].items()}
(root/'web/modules/artwork/artwork-names.js').write_text('// Exact names from the game catalogue and tool definitions.\nexport const artworkNames='+json.dumps(names,ensure_ascii=False,sort_keys=True)+';\n')
print(json.dumps({'ready':len(ready),'total':len(manifest['entries'])}))
